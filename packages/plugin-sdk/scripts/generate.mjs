import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

import Ajv2020 from 'ajv/dist/2020.js'
import ucs2length from 'ajv/dist/runtime/ucs2length.js'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { compile } from 'json-schema-to-typescript'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schema = JSON.parse(readFileSync(resolve(root, 'schema/v1/protocol.schema.json'), 'utf8'))
const registry = JSON.parse(readFileSync(resolve(root, 'schema/registry.json'), 'utf8'))
const require = createRequire(import.meta.url)
const check = process.argv.includes('--check')
const names = Object.keys(schema.$defs)

/** Only the registered, closed local subset can enter build-time code generation. */
export function checkSchema(value) {
  if (!value || typeof value !== 'object') return
  for (const [key, child] of Object.entries(value)) {
    if (
      key === '$ref' &&
      (typeof child !== 'string' ||
        !child.startsWith('#/$defs/') ||
        !names.includes(child.slice(8)))
    )
      throw new Error('Unregistered or remote schema reference')
    if (['pattern', 'patternProperties', '$dynamicRef', 'unevaluatedProperties'].includes(key))
      throw new Error(`Unsupported schema keyword: ${key}`)
    checkSchema(child)
  }
}
checkSchema(schema)
if (schema.$id !== registry.schemaId) throw new Error('Schema registry drift')
const ajv = new Ajv2020.default({
  strict: true,
  ownProperties: true,
  inlineRefs: false,
  code: { source: true, esm: true, lines: true },
})
ajv.addSchema(schema)
const validators = Object.fromEntries(
  names.map((name) => [`validate${name}`, `${schema.$id}#/$defs/${name}`]),
)
let code = standaloneCode.default(ajv, validators)
// AJV's only runtime helper for this subset is pure Unicode code-point counting.
// Inline its build-time source so the shipped validator has no AJV dependency.
code = code.replaceAll(
  'require("ajv/dist/runtime/ucs2length").default',
  `(${ucs2length.default.toString()})`,
)
if (/\brequire\s*\(|\bimport\s|new Function|\beval\s*\(/.test(code))
  throw new Error('Standalone validator contains runtime dependencies or code generation')
const types = await compile(schema, 'PluginProtocol', {
  bannerComment: '/* Generated from schema/v1/protocol.schema.json. Do not edit. */',
  additionalProperties: false,
  unreachableDefinitions: true,
  unknownAny: true,
  strictIndexSignatures: true,
  $refOptions: { resolve: { http: false, file: false } },
})
const declarations =
  names
    .map((name) => `export declare const validate${name}: (value: unknown) => boolean`)
    .join('\n') + '\n'
const constants = `// Generated from schema/registry.json. Do not edit.\nexport const PROTOCOL_REGISTRY = ${JSON.stringify(registry)} as const\n`
const selectors = `// Generated schema selectors. Do not edit.\nimport type * as Protocol from './protocol.ts'\nexport interface SchemaTypes {\n${names.map((name) => `${name}: Protocol.${name}`).join('\n')}\n}\n`
const files = {
  'protocol.ts': types,
  'validators.js': `/* oxlint-disable -- Generated AJV control flow; verified by corpus and drift checks. */\n// Generated by AJV standalone. Do not edit.\n${code}\n`,
  'validators.d.ts': declarations,
  'registry.ts': constants,
  'schema-types.ts': selectors,
}
mkdirSync(resolve(root, 'src/generated'), { recursive: true })
for (const [name, content] of Object.entries(files)) {
  const path = resolve(root, 'src/generated', name)
  // Use the repository formatter in both modes so check is byte-for-byte stable.
  const formatter = resolve(dirname(require.resolve('oxfmt/package.json')), 'bin/oxfmt')
  const formatted = execFileSync(process.execPath, [formatter, '--stdin-filepath', path], {
    input: content,
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
  })
  if (check) {
    if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== formatted)
      throw new Error(`Generated artifact drift: ${name}`)
  } else writeFileSync(path, formatted)
}
console.log(`SDK generated artifacts ${check ? 'match' : 'updated'} (${names.length} definitions).`)
