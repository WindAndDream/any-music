"""Build the reviewed no-eval variant. Requires Emscripten 3.1.65, Python 3.

Usage: python build-engine.py /path/to/quickjs-emscripten-v0.31.0
The source checkout must be the pinned commit; build outputs stay in that checkout.
No plugin source, project hook, downloaded executable or bytecode is accepted.
"""
import hashlib
import json
import pathlib
import re
import subprocess
import sys

source = pathlib.Path(sys.argv[1]).resolve()
package = pathlib.Path(__file__).resolve().parents[1]
commit = '235f6da2fd4f7354fa4765fde4aea880d2a4aef5'
assert subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip() == commit
assert '3.1.65' in subprocess.check_output(['emcc', '--version'], text=True)
engine = source / 'vendor/quickjs/quickjs.c'
original = subprocess.check_output(['git', '-C', str(source), 'show', 'HEAD:vendor/quickjs/quickjs.c'])
text = original.decode()
# Every direct/indirect eval and every function constructor uses JS_EvalObject.
# The trusted C API JS_EvalThis remains available exclusively to the host bridge.
patches = [
    ('static JSValue JS_EvalObject(JSContext *ctx, JSValueConst this_obj,\n                             JSValueConst val, int flags, int scope_idx)\n{',
     '\n    return JS_ThrowTypeError(ctx, "Dynamic code evaluation disabled by Profile 1");\n'),
    ('static JSValue js_dynamic_import(JSContext *ctx, JSValueConst specifier)\n{',
     '\n    return JS_ThrowTypeError(ctx, "External modules disabled by Profile 1");\n'),
]
for marker, insertion in patches:
    assert text.count(marker) == 1, marker
    text = text.replace(marker, marker + insertion)
engine.write_text(text)
build = source / 's11-build'
build.mkdir(exist_ok=True)
interface = (source / 'c/interface.c').read_text()
symbols = ['_malloc', '_free'] + ['_' + name for ret, name in re.findall(
    r'^([\w()* ]+[\s*]+)(QTS_\w+)\(.*?\) ?\{', interface, re.M)
    if 'AsyncifyOnly' not in ret]
(build / 'symbols.json').write_text(json.dumps(symbols))
common = ['-Oz', '-flto', '-D_GNU_SOURCE', '-DCONFIG_BIGNUM', '-DCONFIG_STACK_CHECK',
          '-DCONFIG_VERSION="2024-02-14"', '-ffile-prefix-map=' + str(source) + '=.',
          '-s', 'DYNAMIC_EXECUTION=0']
objects = []
for path in [source / 'c/interface.c'] + [source / 'vendor/quickjs' / (name + '.c') for name in
        ['quickjs', 'libregexp', 'libunicode', 'cutils', 'quickjs-libc', 'libbf']]:
    obj = build / (path.stem + '.o')
    subprocess.run(['emcc', *common, '-c', str(path), '-o', str(obj)], check=True)
    objects.append(str(obj))
out = package / 'engine'
out.mkdir(exist_ok=True)
subprocess.run(['emcc', *common, *objects, '--no-entry', '-o', str(out / 'loader.mjs'),
    '-s', 'EXPORTED_FUNCTIONS=@' + str(build / 'symbols.json'),
    '-s', 'EXPORTED_RUNTIME_METHODS=@' + str(source / 'exportedRuntimeMethods.json'),
    '-s', 'MODULARIZE=1', '-s', 'EXPORT_ES6=1', '-s', 'ENVIRONMENT=web,worker',
    '-s', 'FILESYSTEM=0', '-s', 'IMPORTED_MEMORY=1', '-s', 'ALLOW_MEMORY_GROWTH=1',
    '-s', 'INITIAL_MEMORY=16777216', '-s', 'MAXIMUM_MEMORY=134217728',
    '-s', 'STACK_SIZE=5242880', '-s', 'ALLOW_TABLE_GROWTH=1',
    '--pre-js', str(source / 'templates/pre-extension.js'),
    '--pre-js', str(source / 'templates/pre-wasmMemory.js')], check=True)
(out / 'loader.wasm').replace(out / 'quickjs-noeval.wasm')
# No relative engine URL is ever fetched. Resources must be injected after hash validation.
loader_path = out / 'loader.mjs'
loader = loader_path.read_text()
marker = 'new URL("loader.wasm",import.meta.url).href'
assert loader.count(marker) == 1
loader_path.write_text(loader.replace(marker, '"unavailable-profile-resource"'))
for name in ['LICENSE', 'vendor/quickjs/LICENSE']:
    (out / ('LICENSE-quickjs' if '/' in name else 'LICENSE-bindings')).write_bytes((source / name).read_bytes())
hashes = {name: hashlib.sha256((out / name).read_bytes()).hexdigest() for name in ['loader.mjs', 'quickjs-noeval.wasm']}
record = {'upstreamCommit': commit, 'engineVersion': '0.31.0-am1', 'emscripten': '3.1.65',
          'memoryMaximumBytes': 134217728, 'dynamicExecution': False, 'hashes': hashes,
          'sourceSha256': hashlib.sha256(original).hexdigest(), 'patchedSourceSha256': hashlib.sha256(text.encode()).hexdigest()}
(out / 'build.json').write_text(json.dumps(record, indent=2) + '\n')
(package / 'src/engine-hashes.ts').write_text('// Generated by scripts/build-engine.py.\nexport const ENGINE_HASHES = {\n' +
    ''.join("  '" + name + "': '" + value + "',\n" for name, value in hashes.items()) + '} as const\n')
