fn main() {
    // Compile only our fixed executor/Worker. Cargo never loads a plugin project or config.
    if !matches!(
        std::env::var("CARGO_CFG_TARGET_OS").as_deref(),
        Ok("android" | "ios")
    ) {
        let resources = std::process::Command::new("node")
            .arg("../scripts/build-plugin-executor.mjs")
            .status()
            .expect("Node is required to build the trusted executor resources");
        assert!(
            resources.success(),
            "trusted executor resource build failed"
        );
    }
    for path in [
        "src/lib.rs",
        "src/plugins",
        "src/plugins.rs",
        "src/storage/plugins.rs",
        "permissions",
        "capabilities",
        "../../../crates",
        "../../../Cargo.lock",
        "tauri.conf.json",
        "../src/plugin-executor",
        "../scripts/build-plugin-executor.mjs",
        "../../../packages/plugin-vm/src",
        "../../../packages/plugin-sandbox-browser/src",
        "../../../packages/plugin-sdk/src",
    ] {
        println!("cargo:rerun-if-changed={path}");
    }
    // Cargo examples do not inherit Tauri's executable resource manifest. Dialog
    // imports require Common Controls v6 before any WebView can be constructed.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows")
        && (std::env::var_os("CARGO_FEATURE_S03_ISOLATION_PROBE").is_some()
            || std::env::var_os("CARGO_FEATURE_S15_ACCEPTANCE").is_some())
    {
        println!("cargo:rustc-link-arg-examples=/MANIFEST:EMBED");
        println!(
            "cargo:rustc-link-arg-examples=/MANIFESTDEPENDENCY:type='win32' name='Microsoft.Windows.Common-Controls' version='6.0.0.0' processorArchitecture='*' publicKeyToken='6595b64144ccf1df' language='*'"
        );
    }
    // Derive ACL coverage from the same registry compiled by invoke_handler.
    // A new command must never silently regain Tauri's unrestricted app default.
    println!("cargo:rerun-if-changed=src/ipc.rs");
    let source = include_str!("src/ipc.rs");
    let registry = source
        .split_once("tauri::generate_handler![")
        .expect("application command registry")
        .1
        .split_once(']')
        .expect("closed application command registry")
        .0;
    let commands: Vec<&'static str> = registry
        .split(',')
        .map(str::trim)
        .filter(|path| !path.is_empty())
        .map(|path| path.rsplit("::").next().unwrap())
        .collect();
    assert_eq!(
        commands.len(),
        commands
            .iter()
            .collect::<std::collections::HashSet<_>>()
            .len()
    );
    // Tauri generates permissions for current commands but leaves files from removed ones.
    // Retire those generated definitions before collecting the application's ACL manifest.
    let generated = std::path::Path::new("permissions/autogenerated");
    if generated.exists() {
        for entry in std::fs::read_dir(generated).expect("generated command permissions") {
            let entry = entry.expect("generated permission entry");
            let path = entry.path();
            if entry
                .file_type()
                .expect("generated permission type")
                .is_file()
                && path
                    .extension()
                    .is_some_and(|extension| extension == "toml")
                && path
                    .file_stem()
                    .and_then(|name| name.to_str())
                    .is_some_and(|name| !commands.contains(&name))
            {
                std::fs::remove_file(path).expect("retire removed command permission");
            }
        }
    }
    // AppManifest requires a static slice; this one allocation lives for the build process.
    let commands = Box::leak(commands.into_boxed_slice());
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(commands)),
    )
    .expect("application permission manifest");
}
