import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const read = (path) => readFileSync(resolve(root, path))
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex')
const engineRoot = 'packages/plugin-vm/engine/'
const build = JSON.parse(read(engineRoot + 'build.json'))
for (const [name, expected] of Object.entries(build.hashes)) {
  assert.equal(hash(read(engineRoot + name)), expected, `Engine artifact drift: ${name}`)
  assert.ok(read('packages/plugin-vm/src/engine-hashes.ts').toString().includes(expected))
}
assert.equal(build.dynamicExecution, false)
assert.equal(build.memoryMaximumBytes, 134217728)
assert.equal(build.upstreamCommit, '235f6da2fd4f7354fa4765fde4aea880d2a4aef5')
const files = [
  'packages/plugin-vm/engine/build.json',
  'packages/plugin-vm/scripts/build-engine.py',
  ...['profile.ts', 'guest-bootstrap.ts', 'plugin-vm.ts', 'contracts.ts', 'admission.ts'].map(
    (name) => 'packages/plugin-vm/src/' + name,
  ),
  ...['worker.ts', 'worker-runtime.ts', 'sandbox-session.ts'].map(
    (name) => 'packages/plugin-sandbox-browser/src/' + name,
  ),
  'packages/plugin-testkit/src/test-host.ts',
  'packages/plugin-sandbox-browser/src/browser.ts',
  'packages/plugin-sandbox-browser/scripts/build.mjs',
].toSorted()
const sources = Object.fromEntries(files.map((path) => [path, hash(read(path))]))
const profileHash = hash(JSON.stringify(sources))
const identityPath = 'packages/plugin-vm/src/profile-identity.ts'
const identity = `// Generated by scripts/check-plugin-vm.mjs --write.\nexport const VM_PROFILE_HASH = '${profileHash}'\n`
const record =
  JSON.stringify({ profileId: 'am-quickjs-noeval-desktop-v1', profileHash, sources }, null, 2) +
  '\n'
if (process.argv.includes('--write')) {
  writeFileSync(resolve(root, identityPath), identity)
  writeFileSync(resolve(root, engineRoot + 'profile.json'), record)
} else {
  assert.equal(
    read(identityPath).toString(),
    identity,
    'Profile source drift; review and regenerate identity',
  )
  assert.equal(read(engineRoot + 'profile.json').toString(), record, 'Profile record drift')
}
console.log(
  JSON.stringify({
    profileHash,
    wasmSha256: build.hashes['quickjs-noeval.wasm'],
    offlineOnly: true,
    nativeTargetAdmission: 'separate exact target record',
  }),
)
